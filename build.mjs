#!/usr/bin/env node
// Bundles the ES modules into one classic script so index.html works when opened directly
// (file://, GitHub Pages, the native shell) with no module loader, stamps the build number
// into the page and the service worker, fingerprints the artwork, and writes dist/ for the
// native shell. Run: node build.mjs   (or: npm run build)
import { readFileSync, writeFileSync, readdirSync, unlinkSync, existsSync, rmSync, mkdirSync, copyFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ORDER = ['geo', 'osm', 'vectortiles', 'landscape', 'elevation', 'landcover', 'graph', 'cues', 'planner', 'places', 'details', 'spots', 'cache', 'engine', 'navigation', 'settings', 'journal', 'native', 'app'];
const root = dirname(fileURLToPath(import.meta.url));
const at = (...p) => join(root, ...p);
const read = (p) => readFileSync(at(p), 'utf8');
const sha1 = (data) => createHash('sha1').update(data).digest('hex').slice(0, 8);
const fail = (msg) => { console.error(msg); process.exit(1); };

// Every module shares one scope in the bundle, so a top-level name declared twice (two
// modules each with `const HEBREW`) breaks the whole app at load. Fail here instead.
const seen = new Map();
for (const name of ORDER) {
  const src = read(`js/${name}.js`);
  for (const m of src.matchAll(/^(?:export\s+)?(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm)) {
    if (seen.has(m[1])) fail(`build: top-level name '${m[1]}' is declared in both js/${seen.get(m[1])}.js and js/${name}.js (the bundle shares one scope)`);
    seen.set(m[1], name);
  }
}
const parts = [];
for (const name of ORDER) {
  let src = read(`js/${name}.js`);
  src = src.replace(/^import [^;]*? from '[^']*';[ \t]*$/gms, '');
  src = src.replace(/^export (?=(async |const |function |class |let ))/gm, '');
  const left = src.match(/^(?:import|export)\b.*$/m);
  if (left) fail(`build: ${name}.js has a form the bundler cannot strip: ${JSON.stringify(left[0])}`);
  parts.push(`// ---- ${name}.js ----\n${src}`);
}
const out = '// Generated by build.mjs from js/*.js. Do not edit by hand.\n(function () {\n"use strict";\n' + parts.join('\n') + '\n})();\n';
writeFileSync(at('js/bundle.js'), out);
console.log('wrote js/bundle.js', Buffer.byteLength(out), 'bytes');

// Fingerprint the artwork: every img/<name>.png the page uses is published as
// img/<name>.<hash>.png (hash of its bytes). A new file name can never be confused with an
// old cached copy, by a browser or by GitHub's CDN. Sources stay as img/<name>.png; older
// fingerprinted copies of the same name are removed.
const fingerprint = new Map();
const pics = readdirSync(at('img')).filter((f) => /\.(png|jpg|mp4|webm)$/.test(f)).sort();
for (const file of pics) {
  if (/\.[0-9a-f]{8}\.(png|jpg|mp4|webm)$/.test(file)) continue; // a published copy, handled below
  const ext = file.match(/\.(\w+)$/)[1];
  const stem = file.slice(0, -(ext.length + 1));
  const bytes = readFileSync(at('img', file));
  const pub = `${stem}.${sha1(bytes)}.${ext}`;
  for (const old of pics) if (old !== pub && new RegExp(`^${stem.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\.[0-9a-f]{8}\\.${ext}$`).test(old)) unlinkSync(at('img', old));
  if (!existsSync(at('img', pub))) writeFileSync(at('img', pub), bytes);
  fingerprint.set(file, pub);
}
// img/name.png or img/name.<oldhash>.png (with or without ?v=) -> img/name.<hash>.png; same for .jpg
const publishRefs = (text) => text.replace(/img\/([\w-]+?)(?:\.[0-9a-f]{8})?\.(png|jpg|mp4|webm)(?:\?v=[0-9a-f]+)?/g, (_, stem, ext) => 'img/' + (fingerprint.get(`${stem}.${ext}`) || `${stem}.${ext}`));

// Stamp the build into index.html (cache-busting query on the bundle and stylesheet) and
// sw.js (the service worker's cache name), so phones that installed the app pick up a new
// build on their next visit. The manifest is versioned too (GitHub's edge cache once held an
// old one for hours, so a fresh install got the old icons).
const css = read('css/style.css');
let plainHtml = publishRefs(read('index.html').replace(/(js\/bundle\.js|css\/style\.css|manifest\.webmanifest)\?v=[0-9a-f]+/g, '$1'));
plainHtml = plainHtml.replace(/<span id="buildTag" data-build="[^"]*">[^<]*<\/span>/, '<span id="buildTag" data-build="dev">dev</span>');
const plainSw = publishRefs(read('sw.js').replace(/const CACHE_VERSION = '[^']*';/, "const CACHE_VERSION = '';"));
const man = publishRefs(read('manifest.webmanifest'));
writeFileSync(at('manifest.webmanifest'), man);
const h = sha1('v5' + out + css + plainHtml + plainSw + man);
let stamped = plainHtml.replace(/(src|href)="(js\/bundle\.js|css\/style\.css|manifest\.webmanifest)"/g, (_, a, b) => `${a}="${b}?v=${h}"`);
// The build number is shown in the menu ("Version 1a2b3c4d"), so anyone can tell which build they see.
stamped = stamped.replace(/<span id="buildTag" data-build="[^"]*">[^<]*<\/span>/, `<span id="buildTag" data-build="${h}">${h}</span>`);
writeFileSync(at('index.html'), stamped);
writeFileSync(at('sw.js'), plainSw.replace("const CACHE_VERSION = '';", `const CACHE_VERSION = '${h}';`));
console.log('build', h, '| artwork:', [...fingerprint.values()].sort().join(', '));

// The native shell (Capacitor) takes the published web app from dist/: the page, the bundle,
// the styles, the artwork and the manifest, nothing else (no tests, no node_modules).
const dist = at('dist');
if (existsSync(dist)) rmSync(dist, { recursive: true });
for (const d of ['js/vendor', 'css', 'img']) mkdirSync(join(dist, d), { recursive: true });
for (const f of ['index.html', 'manifest.webmanifest', 'sw.js', 'js/bundle.js', 'js/vendor/capacitor.js', 'js/vendor/leaflet.js', 'js/vendor/leaflet.css', 'css/style.css']) copyFileSync(at(f), join(dist, f));
for (const pub of fingerprint.values()) copyFileSync(at('img', pub), join(dist, 'img', pub));
console.log('dist/ ready for the native shell');
