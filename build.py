# Bundles the ES modules into one classic script so index.html works when opened
# directly from Finder (file://), with no local server. Run: python3 build.py
import re, pathlib
ORDER = ['geo', 'osm', 'vectortiles', 'landscape', 'elevation', 'landcover', 'graph', 'cues', 'planner', 'places', 'details', 'spots', 'cache', 'engine', 'navigation', 'settings', 'journal', 'native', 'app']
root = pathlib.Path(__file__).parent
parts = []
# Every module shares one scope in the bundle, so a top-level name declared twice (two
# modules each with `const HEBREW`) breaks the whole app at load. Fail here instead.
seen = {}
for name in ORDER:
    src = pathlib.Path('js') / f'{name}.js'
    for m in re.finditer(r'^(?:export\s+)?(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)', src.read_text(encoding='utf-8'), re.M):
        ident = m.group(1)
        if ident in seen: raise SystemExit(f'build: top-level name {ident!r} is declared in both js/{seen[ident]}.js and js/{name}.js (the bundle shares one scope)')
        seen[ident] = name
for name in ORDER:
    src = (root / 'js' / f'{name}.js').read_text(encoding='utf-8')
    src = re.sub(r'^import [^;]*? from \'[^\']*\';[ \t]*$', '', src, flags=re.M | re.S)
    src = re.sub(r'^export (?=(async |const |function |class |let ))', '', src, flags=re.M)
    left = re.findall(r'^(?:import|export)\b.*$', src, flags=re.M)
    if left:
        raise SystemExit(f'build: {name}.js has a form the bundler cannot strip: {left[0]!r}')
    parts.append(f'// ---- {name}.js ----\n{src}')
out = '// Generated by build.py from js/*.js. Do not edit by hand.\n(function () {\n"use strict";\n' + '\n'.join(parts) + '\n})();\n'
(root / 'js' / 'bundle.js').write_text(out, encoding='utf-8')
print('wrote js/bundle.js', len(out), 'bytes')

# Fingerprint the artwork: every img/<name>.png the page uses is published as
# img/<name>.<hash>.png (hash of its bytes). A new file name can never be confused
# with an old cached copy, by a browser or by GitHub's CDN. Sources stay as img/<name>.png;
# older fingerprinted copies of the same name are removed.
import hashlib
imgdir = root / 'img'
fingerprint = {}
for p in sorted(imgdir.glob('*.png')):
    if re.search(r'\.[0-9a-f]{8}\.png$', p.name):
        continue  # a published copy, handled below
    fh = hashlib.sha1(p.read_bytes()).hexdigest()[:8]
    pub = imgdir / f'{p.stem}.{fh}.png'
    for old in imgdir.glob(f'{p.stem}.????????.png'):
        if old != pub and re.fullmatch(re.escape(p.stem) + r'\.[0-9a-f]{8}\.png', old.name):
            old.unlink()
    if not pub.exists():
        pub.write_bytes(p.read_bytes())
    fingerprint[p.name] = pub.name
def publish_refs(text):
    # img/name.png or img/name.<oldhash>.png (with or without ?v=) -> img/name.<hash>.png
    return re.sub(r'img/([\w-]+?)(?:\.[0-9a-f]{8})?\.png(?:\?v=[0-9a-f]+)?', lambda m: 'img/' + fingerprint.get(m.group(1) + '.png', m.group(1) + '.png'), text)

# Stamp the build into index.html (cache-busting query on the bundle and stylesheet) and sw.js
# (the service worker's cache name), so phones that installed the app pick up a new
# build on their next visit.
idx = root / 'index.html'
sw = root / 'sw.js'
man = root / 'manifest.webmanifest'
css = (root / 'css' / 'style.css').read_text(encoding='utf-8')
plain_html = publish_refs(re.sub(r'(js/bundle\.js|css/style\.css|manifest\.webmanifest)\?v=[0-9a-f]+', r'\1', idx.read_text(encoding='utf-8')))
plain_html = re.sub(r'<span id="buildTag" data-build="[^"]*">[^<]*</span>', '<span id="buildTag" data-build="dev">dev</span>', plain_html)
plain_sw = publish_refs(re.sub(r"const CACHE_VERSION = '[^']*';", "const CACHE_VERSION = '';", sw.read_text(encoding='utf-8')))
man.write_text(publish_refs(man.read_text(encoding='utf-8')), encoding='utf-8')
h = hashlib.sha1(('v5' + out + css + plain_html + plain_sw + man.read_text(encoding='utf-8')).encode()).hexdigest()[:8]
# The manifest is versioned too: GitHub's edge cache held an old one for hours, so a fresh
# install got the old icons (and no app name).
stamped = re.sub(r'(src|href)="(js/bundle\.js|css/style\.css|manifest\.webmanifest)"', lambda m: f'{m.group(1)}="{m.group(2)}?v={h}"', plain_html)
# The build number is shown in the menu ("Version 1a2b3c4d"), so anyone can tell which build they see.
stamped = re.sub(r'<span id="buildTag" data-build="[^"]*">[^<]*</span>', f'<span id="buildTag" data-build="{h}">{h}</span>', stamped)
idx.write_text(stamped, encoding='utf-8')
sw.write_text(plain_sw.replace("const CACHE_VERSION = '';", f"const CACHE_VERSION = '{h}';"), encoding='utf-8')
print('build', h, '| artwork:', ', '.join(sorted(fingerprint.values())))

# The native shell (Capacitor) takes the published web app from dist/: the page, the bundle,
# the styles, the artwork and the manifest, nothing else (no tests, no node_modules).
import shutil
Path = pathlib.Path
dist = Path('dist')
if dist.exists(): shutil.rmtree(dist)
(dist / 'js').mkdir(parents=True)
(dist / 'css').mkdir()
(dist / 'img').mkdir()
shutil.copy('index.html', dist / 'index.html')
shutil.copy('manifest.webmanifest', dist / 'manifest.webmanifest')
shutil.copy('sw.js', dist / 'sw.js')
shutil.copy('js/bundle.js', dist / 'js' / 'bundle.js')
shutil.copy('css/style.css', dist / 'css' / 'style.css')
for name in fingerprint.values(): shutil.copy(Path('img') / name, dist / 'img' / name)
print('dist/ ready for the native shell')
