# Bundles the ES modules into one classic script so index.html works when opened
# directly from Finder (file://), with no local server. Run: python3 build.py
import re, pathlib
ORDER = ['geo', 'osm', 'vectortiles', 'landscape', 'elevation', 'graph', 'cues', 'planner', 'places', 'details', 'spots', 'cache', 'engine', 'navigation', 'app']
root = pathlib.Path(__file__).parent
parts = []
for name in ORDER:
    src = (root / 'js' / f'{name}.js').read_text()
    src = re.sub(r'^import .*?;\s*$', '', src, flags=re.M | re.S)
    src = re.sub(r'^export (?=(async |const |function |class |let ))', '', src, flags=re.M)
    parts.append(f'// ---- {name}.js ----\n{src}')
out = '// Generated by build.py from js/*.js. Do not edit by hand.\n(function () {\n"use strict";\n' + '\n'.join(parts) + '\n})();\n'
(root / 'js' / 'bundle.js').write_text(out)
print('wrote js/bundle.js', len(out), 'bytes')

# Stamp the build into index.html (cache-busting query on the bundle and stylesheet) and sw.js
# (the service worker's cache name), so phones that installed the app pick up a new
# build on their next visit.
import hashlib
idx = root / 'index.html'
sw = root / 'sw.js'
css = (root / 'css' / 'style.css').read_text()
plain_html = re.sub(r'(js/bundle\.js|css/style\.css)\?v=[0-9a-f]+', r'\1', idx.read_text())
plain_sw = re.sub(r"const CACHE_VERSION = '[^']*';", "const CACHE_VERSION = '';", sw.read_text())
h = hashlib.sha1(('v2' + out + css + plain_html + plain_sw).encode()).hexdigest()[:8]  # 'v2': stylesheet is cache-busted too
idx.write_text(plain_html.replace('js/bundle.js"', f'js/bundle.js?v={h}"').replace('css/style.css"', f'css/style.css?v={h}"'))
sw.write_text(plain_sw.replace("const CACHE_VERSION = '';", f"const CACHE_VERSION = '{h}';"))
print('build', h)
